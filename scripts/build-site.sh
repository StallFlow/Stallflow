#!/usr/bin/env bash
# Builds the GitHub Pages site: one copy of web/ per stall in stalls/<slug>/,
# each with its own config.js. Output goes to _site/.
#
#   stallflow.github.io/Stallflow/<slug>/       the customer order page
#   stallflow.github.io/Stallflow/<slug>/app/   the staff app
#
# Usage: scripts/build-site.sh [build-id]
set -euo pipefail
cd "$(dirname "$0")/.."

BUILD="${1:-$(git rev-parse --short HEAD 2>/dev/null || date +%s)}"
OUT=_site
rm -rf "$OUT"
mkdir -p "$OUT"
touch "$OUT/.nojekyll"
cp web/landing.html "$OUT/index.html"

for dir in stalls/*/; do
  slug="$(basename "$dir")"
  conf="$dir/stall.json"
  [ -f "$conf" ] || continue

  api="$(node -e 'const c=require(process.argv[1]); process.stdout.write(c.api||"")' "$PWD/$conf")"
  if [ -z "$api" ]; then
    echo "skip $slug: no api address in $conf" >&2
    continue
  fi

  mkdir -p "$OUT/$slug"
  cp -r web/app web/core web/plugins web/index.html "$OUT/$slug/"
  node -e '
    const c = require(process.argv[1]);
    const cfg = { api: c.api, stall: process.argv[2] };
    process.stdout.write(
      "/* Generated by scripts/build-site.sh from stalls/" + process.argv[2] +
      "/stall.json. Do not edit here. */\nwindow.STALLFLOW = " +
      JSON.stringify(cfg, null, 2) + ";\n");
  ' "$PWD/$conf" "$slug" > "$OUT/$slug/config.js"
  sed -i "s/__BUILD__/$BUILD/g" "$OUT/$slug/app/sw.js"
  echo "built $slug"
done
